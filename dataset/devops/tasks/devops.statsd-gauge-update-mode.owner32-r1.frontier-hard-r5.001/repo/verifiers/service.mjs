import {createServer} from 'node:http';
import {createSocket} from 'node:dgram';
import {readFileSync} from 'node:fs';
import {randomBytes} from 'node:crypto';
let port=57100,host='127.0.0.1',profile='A',form='batched-valid-lines';
for(let i=2;i<process.argv.length;i++){if(process.argv[i]==='--port')port=Number(process.argv[++i]);else if(process.argv[i]==='--host')host=process.argv[++i];else if(process.argv[i]==='--profile')profile=process.argv[++i];else if(process.argv[i]==='--form')form=process.argv[++i];}
const plan=JSON.parse(readFileSync(new URL('./profiles.json',import.meta.url)));
const chosen=plan.profiles.find(p=>p.id===profile);if(!chosen)throw new Error('unknown profile');
// Relay announce batches are generated by the relay itself and are never split;
// only live-forwarded traffic groups decompose under the whole-line transport form.
const groups=form==='split-whole-lines'?chosen.groups.flatMap(g=>g.announce?[g]:g.lines.map(line=>({source:g.source,announce:false,lines:[line]}))):chosen.groups;
const wirePlan=groups.map(g=>({source:g.source,announce:g.announce,lines:g.lines,base64:Buffer.from(g.lines.map(line=>`${line.identity}:${line.token}|g`).join('\n'),'ascii').toString('base64')}));
const token=process.env.GAUGE_AUDIT_TOKEN||randomBytes(32).toString('hex');
const udp=createSocket('udp4');
const senders=new Map(chosen.relays.map(f=>[f.id,createSocket('udp4')]));
const senderPort=new Map(chosen.relays.map(f=>[f.id,port+f.port_offset]));
const sourceByPort=new Map(chosen.relays.map(f=>[port+f.port_offset,f.id]));
let ready=false,epoch=0,seeded=false,running=false,receipts=[],writer=[],history=[],state=new Map(),committedReceipt=0,transportErrors=[],contamination=[],sinkErrors=[],controls=[],pendingWitness=null,archive=[];
const clone=x=>JSON.parse(JSON.stringify(x));const now=()=>performance.now();
const planIdentities=[...new Set(chosen.groups.flatMap(g=>g.lines.map(line=>line.identity)))];
const identities=[...chosen.identities,...planIdentities.filter(i=>!chosen.identities.includes(i))];
function snapshot(){return {profile,form,epoch,seeded,running,identities,receipts:clone(receipts),history:clone(history),state:Object.fromEntries(state),committedReceipt};}
function audit(){return {...snapshot(),clockNow:now(),convention:chosen.convention,writer:clone(writer),transportErrors:clone(transportErrors),contamination:clone(contamination),sinkErrors:clone(sinkErrors),controls:clone(controls),archive:clone(archive),socketIdentity:{receiver:udp.address(),senders:Object.fromEntries([...senders].map(([id,socket])=>[id,socket.address()]))}};}
function send(r,status,obj){r.writeHead(status,{'content-type':'application/json','cache-control':'no-store'});r.end(JSON.stringify(obj));}
async function body(q){let x='';for await(const part of q){x+=part;if(x.length>1000000)throw new Error('oversize');}return x?JSON.parse(x):{};}
function freeCheck(protocol,p){
 for(const suffix of [protocol,protocol+'6']){
  for(const line of readFileSync('/proc/net/'+suffix,'utf8').trim().split('\n').slice(1)){
   const f=line.trim().split(/\s+/);const n=parseInt(f[1].split(':').pop(),16);
   if(n===p&&(protocol==='udp'||f[3]==='0A'))throw new Error('Port busy before own binding: '+protocol+'/'+p);
  }
 }
}
udp.on('message',(bytes,peer)=>{
 const pending=pendingWitness;
 const source=peer.address==='127.0.0.1'?sourceByPort.get(peer.port):undefined;
 if(!pending||!source||peer.port!==pending.sourcePort){contamination.push({at:now(),peer,base64:bytes.toString('base64')});return;}
 const receipt={sequence:receipts.length+1,epoch,source,base64:bytes.toString('base64'),text:bytes.toString('ascii'),bytes:bytes.length,receivedAt:now(),peer};
 receipts.push(receipt);
 if(receipt.base64!==pending.base64)transportErrors.push({kind:'native_byte_mismatch',sequence:receipt.sequence});
 pendingWitness=null;pending.resolve(receipt);
});
udp.on('error',e=>{transportErrors.push({kind:'receiver_socket_error',message:e.message});pendingWitness?.reject(e);pendingWitness=null;});
for(const [id,socket] of senders)socket.on('error',e=>{transportErrors.push({kind:'writer_socket_error',relay:id,message:e.message});pendingWitness?.reject(e);pendingWitness=null;});
async function produce(){
 try{
  for(const [index,entry] of wirePlan.entries()){
   const bytes=Buffer.from(entry.base64,'base64');
   const socket=senders.get(entry.source);
   const sourcePort=senderPort.get(entry.source);
   let timer;
   const witnessed=new Promise((resolve,reject)=>{pendingWitness={base64:entry.base64,sourcePort,resolve,reject};timer=setTimeout(()=>{pendingWitness=null;reject(new Error('native receipt missing'));},500);});
   // Exactly one send per datagram from its relay's own socket.
   // A missing native receipt is retained, never resent.
   const record={sequence:index+1,epoch,sentAt:now(),source:entry.source,announce:entry.announce,base64:entry.base64,bytes:bytes.length,lines:clone(entry.lines),sent:false};writer.push(record);
   socket.send(bytes,port,'127.0.0.1',err=>{record.sent=!err;if(err){record.sendError=err.message;pendingWitness?.reject(err);pendingWitness=null;}});
   try{const rx=await witnessed;record.witnessSequence=rx.sequence;}finally{clearTimeout(timer);}
   await new Promise(resolve=>setTimeout(resolve,30));
  }
 }catch(e){transportErrors.push({kind:'native_transport_failure',message:e.message});}
 finally{running=false;}
}
function clear(){
 if(receipts.length||history.length||writer.length)archive.push({epoch,writer:clone(writer),receipts:clone(receipts),history:clone(history),state:Object.fromEntries(state),transportErrors:clone(transportErrors),contamination:clone(contamination),sinkErrors:clone(sinkErrors)});
 epoch++;receipts=[];writer=[];history=[];state=new Map();committedReceipt=0;transportErrors=[];contamination=[];sinkErrors=[];
}
freeCheck('udp',port);await new Promise((resolve,reject)=>{udp.once('error',reject);udp.bind(port,host,resolve);});
for(const f of chosen.relays){freeCheck('udp',senderPort.get(f.id));await new Promise((resolve,reject)=>{const socket=senders.get(f.id);socket.once('error',reject);socket.bind(senderPort.get(f.id),host,resolve);});}
ready=true;freeCheck('tcp',port);
createServer(async(q,r)=>{try{
 const u=new URL(q.url,'http://receiver.invalid');
 if(u.pathname==='/health')return send(r,ready?200:503,{ready});
 if(u.pathname==='/snapshot')return send(r,200,snapshot());
 if(u.pathname==='/audit'){
  if(q.headers.authorization!=='Bearer '+token)return send(r,403,{error:'admin authentication required'});
  return send(r,200,audit());
 }
 if(u.pathname==='/capture'){
  const after=Number(u.searchParams.get('after')||0);
  return send(r,200,{epoch,running,receipts:clone(receipts.filter(x=>x.sequence>after))});
 }
 if(u.pathname==='/begin'&&q.method==='POST'){
  const x=await body(q);controls.push({kind:x.seed?'seed':'begin',at:now(),epoch});
  if(x.seed&&seeded)return send(r,200,{alreadySeeded:true,epoch});
  if(running)return send(r,409,{error:'producer active'});
  clear();seeded=true;running=true;setImmediate(produce);return send(r,200,{epoch});
 }
 if(u.pathname==='/reset'&&q.method==='POST'){
  controls.push({kind:'reset',at:now(),epoch});
  if(running)return send(r,409,{error:'producer active'});
  clear();seeded=true;return send(r,200,snapshot());
 }
 if(u.pathname==='/ingest'&&q.method==='POST'){
  const x=await body(q);
  if(x.epoch!==epoch)return send(r,409,{error:'stale session'});
  if(!Array.isArray(x.updates))return send(r,422,{error:'updates required'});
  for(const item of x.updates){
   const receipt=receipts.find(rx=>rx.sequence===item.receipt);
   if(!receipt||typeof item.identity!=='string'||!Number.isFinite(item.value)){
    sinkErrors.push({item:clone(item),at:now(),error:'invalid sink event'});return send(r,422,{error:'invalid sink event'});
   }
   const before=state.get(item.identity)??0;
   const record={...clone(item),before,receivedAt:now(),ageMs:now()-receipt.receivedAt};
   state.set(item.identity,item.value);history.push(record);
  }
  committedReceipt=Math.max(committedReceipt,Number(x.receipt)||0);
  return send(r,200,{accepted:x.updates.length});
 }
 send(r,404,{error:'not found'});
 }catch(e){send(r,500,{error:e.message});}
}).listen(port,host);
