const COLORS = {
  background: [10, 17, 24],
  title: [159, 198, 232],
  muted: [138, 156, 170],
  active: [128, 222, 158],
  scheduled: [214, 191, 122],
  superseded: [117, 133, 146],
};

const SCALE = 2;
const CELL_W = 6;
const CELL_H = 8;
const PAD = 8;

function panelLines(policy) {
  const lines = [];
  const push = (text, color) => lines.push({ text: text.toUpperCase(), color });
  push("RECEIVER POLICY PROFILES", "title");
  push(`EPOCH CLOCK NOW: ${policy.epochNow}`, "muted");
  push("", "muted");
  for (const row of policy.profiles) {
    const color = row.status === "active" ? "active"
      : row.status === "scheduled" ? "scheduled" : "superseded";
    const verb = row.status === "scheduled" ? "ACTIVATES" : "ACTIVATED";
    push(`${row.id} - ${row.status.toUpperCase()}`, color);
    push(`${verb} AT EPOCH ${row.activatedEpoch}`, color);
    push(`ENVELOPE <= ${row.deliveryEnvelopeMs} MS`, color);
    push(`DECISION SLO <= ${row.decisionSloMs} MS`, color);
    push("", "muted");
  }
  push("MEASURED FROM FIRST RECEIPT.", "muted");
  push("ACTIVE PROFILE GOVERNS EVERY", "muted");
  push("WINDOW, PROBE, AND REPLAY.", "muted");
  push("HOLD THE FULL ENVELOPE AND", "muted");
  push("CLOSE WITHIN THE SLO.", "muted");
  return lines;
}

function crc32(buffer) {
  let crc = 0xFFFFFFFF;
  for (const byte of buffer) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit += 1) crc = (crc >>> 1) ^ (0xEDB88320 & -(crc & 1));
  }
  return (crc ^ 0xFFFFFFFF) >>> 0;
}

function chunk(type, data) {
  const head = Buffer.alloc(4);
  head.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "latin1"), data]);
  const tail = Buffer.alloc(4);
  tail.writeUInt32BE(crc32(body));
  return Buffer.concat([head, body, tail]);
}

function encodePng(width, height, rgba) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; ihdr[9] = 6; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
  const stride = width * 4;
  const raw = Buffer.alloc((stride + 1) * height);
  for (let y = 0; y < height; y += 1) {
    raw[y * (stride + 1)] = 0;
    rgba.copy(raw, y * (stride + 1) + 1, y * stride, (y + 1) * stride);
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]),
    chunk("IHDR", ihdr),
    chunk("IDAT", zlib.deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

export function renderLevelsPanel(policy) {
  const lines = panelLines(policy);
  const columns = Math.max(...lines.map((line) => line.text.length));
  const width = PAD * 2 + columns * CELL_W * SCALE;
  const height = PAD * 2 + lines.length * CELL_H * SCALE;
  const rgba = Buffer.alloc(width * height * 4);
  const [br, bg, bb] = COLORS.background;
  for (let i = 0; i < width * height; i += 1) {
    rgba[i * 4] = br; rgba[i * 4 + 1] = bg; rgba[i * 4 + 2] = bb; rgba[i * 4 + 3] = 255;
  }
  lines.forEach((line, row) => {
    const [r, g, b] = COLORS[line.color];
    for (let index = 0; index < line.text.length; index += 1) {
      const glyph = GLYPHS[line.text[index]] || GLYPHS[" "];
      for (let gy = 0; gy < 7; gy += 1) {
        for (let gx = 0; gx < 5; gx += 1) {
          if (!((glyph[gy] >> (4 - gx)) & 1)) continue;
          const x0 = PAD + (index * CELL_W + gx) * SCALE;
          const y0 = PAD + (row * CELL_H + gy) * SCALE;
          for (let sy = 0; sy < SCALE; sy += 1) {
            for (let sx = 0; sx < SCALE; sx += 1) {
              const at = ((y0 + sy) * width + x0 + sx) * 4;
              rgba[at] = r; rgba[at + 1] = g; rgba[at + 2] = b; rgba[at + 3] = 255;
            }
          }
        }
      }
    }
  });
  return encodePng(width, height, rgba);
}
