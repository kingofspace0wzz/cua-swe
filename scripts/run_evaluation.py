#!/usr/bin/env python3
"""Public, provider-configurable evaluation of the released domain manifests."""
from __future__ import annotations
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import shutil
import sys
import yaml
from provider_client import ProviderConfig, ProviderError

ROOT = Path(__file__).resolve().parents[1]
EXTENSION_FILES = ('run_evaluation.py', 'provider_client.py', 'run_provider_agent.py',
                   'public_taskbundle.py', 'public_mobile.py', 'provider_relay.py')


def extension_identity():
    return {'name': 'cua-swe-public-api-v1', 'files': {
        name: hashlib.sha256((ROOT / 'scripts' / name).read_bytes()).hexdigest()
        for name in EXTENSION_FILES}}


def select_tasks(domain, scope, task_ids=None):
    suffix = 'json' if domain == 'mobile' else 'yaml'
    path = ROOT / 'dataset' / domain / f'manifest.{suffix}'
    manifest = yaml.safe_load(path.read_text())
    rows = manifest['tasks']
    if task_ids:
        unknown = set(task_ids) - {r['task_id'] for r in rows}
        if unknown:
            raise ValueError('task IDs absent from this domain: ' + ', '.join(sorted(unknown)))
        if len(task_ids) != len(set(task_ids)):
            raise ValueError('duplicate task IDs')
        rows = [r for r in rows if r['task_id'] in task_ids]
    elif scope == 'gate':
        rows = rows[:10]
    return rows, {'path': str(path.relative_to(ROOT)), 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}


def parser():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('action', choices=['plan', 'run'])
    p.add_argument('--domain', required=True, choices=['web', 'game', 'mobile', 'devops'])
    p.add_argument('--scope', choices=['gate', 'full'], default='gate')
    p.add_argument('--task-id', action='append', help='select exact manifest task ID; repeat to select several')
    p.add_argument('--condition', choices=['cua', 'code-only'], default='cua')
    p.add_argument('--provider', required=True, choices=['responses', 'chat-completions', 'anthropic', 'bedrock'])
    p.add_argument('--model', required=True, help='model ID accepted by your endpoint')
    p.add_argument('--base-url', default='')
    p.add_argument('--api-key-env', default='', help='credential environment variable name; NONE for local servers')
    p.add_argument('--region', default='')
    p.add_argument('--max-output-tokens', type=int, default=16384)
    p.add_argument('--request-timeout', type=int, default=600)
    p.add_argument('--output-root', type=Path, help='new directory for this model/domain/condition run')
    p.add_argument('--runtime-config', type=Path, help='Mobile runtime JSON generated by configure_mobile_runtime.py')
    p.add_argument('--max-workers', type=int, default=1, help='TaskBundle parallelism; Mobile runs sequentially')
    return p


def make_plan(args):
    if args.max_workers < 1:
        raise ValueError('--max-workers must be positive')
    if args.domain in {'mobile', 'devops'} and args.max_workers != 1:
        raise ValueError(f'{args.domain} uses --max-workers 1')
    config = ProviderConfig(args.provider, args.model, args.base_url, args.api_key_env,
                            args.region, args.max_output_tokens, args.request_timeout)
    rows, manifest = select_tasks(args.domain, args.scope, args.task_id)
    return {'schema': 1, 'extension': extension_identity(), 'domain': args.domain,
            'condition': args.condition, 'provider': config.public_record(),
            'manifest': manifest, 'tasks': rows, 'task_count': len(rows),
            'attempts_per_task': 1, 'max_workers': args.max_workers,
            'runtime_config': str(args.runtime_config.resolve()) if args.runtime_config else None,
            'output_root': str(args.output_root.resolve()) if args.output_root else None}


def main(argv=None):
    p = parser(); args = p.parse_args(argv)
    try:
        plan = make_plan(args)
        if args.action == 'plan':
            print(json.dumps(plan, indent=2)); return 0
        if args.domain != 'mobile' and Path(sys.prefix).resolve().is_relative_to(ROOT):
            raise ValueError('create the evaluation virtualenv outside the repository; see README Quick start')
        if not args.output_root:
            raise ValueError('run requires --output-root')
        output = args.output_root.resolve()
        if output.exists():
            raise ValueError('--output-root must be a new directory')
        config = ProviderConfig(**plan['provider'])
        token = '' if config.api_key_env == 'NONE' else os.environ.get(config.api_key_env, '')
        if config.api_key_env != 'NONE' and not token:
            raise ValueError(f'set {config.api_key_env} before running')
        if args.domain == 'mobile' and not args.runtime_config:
            raise ValueError('Mobile run requires --runtime-config')
        if args.domain != 'mobile':
            for command in ('bwrap', 'strace', 'codex', 'node', 'cc'):
                if not shutil.which(command):
                    raise ValueError(f'install {command} before running; see README Quick start')
            trace_help = subprocess.run(['strace', '--help'], text=True, capture_output=True, check=True).stdout
            if '--always-show-pid' not in trace_help or '--decode-pids' not in trace_help:
                raise ValueError('upgrade strace to a version with --always-show-pid and --decode-pids=pidns')
        # Validate published task bytes before invoking any model.
        subprocess.run([sys.executable, str(ROOT / 'scripts/check_release.py')], cwd=ROOT, check=True)
        output.mkdir(parents=True)
        plan_path = output / 'evaluation.json'
        plan_path.write_text(json.dumps(plan, indent=2) + '\n')
        env = os.environ.copy()
        env.pop(config.api_key_env, None)
        env.pop('CUA_SWE_PROVIDER_TOKEN', None)
        env['CUA_SWE_PROVIDER_CONFIG'] = json.dumps(config.public_record())
        script = 'public_mobile.py' if args.domain == 'mobile' else 'public_taskbundle.py'
        command = [sys.executable, str(ROOT / 'scripts' / script), str(plan_path)]
        if args.domain == 'mobile':
            env['CUA_SWE_PROVIDER_TOKEN'] = token
            result = subprocess.run(command, cwd=ROOT, env=env)
        else:
            from provider_relay import TOKEN_ENV, relay
            with relay(config, token) as (local, lease_token):
                # The lease token travels in the environment only; the harness hands it to the agent the same way.
                env['CUA_SWE_PROVIDER_CONFIG'] = json.dumps(local.public_record())
                env[TOKEN_ENV] = lease_token
                result = subprocess.run(command, cwd=ROOT, env=env)
        (output / 'completion.json').write_text(json.dumps({'exit_code': result.returncode}) + '\n')
        return result.returncode
    except (ValueError, ProviderError) as exc:
        p.error(str(exc))


if __name__ == '__main__':
    raise SystemExit(main())
